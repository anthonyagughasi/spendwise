function buildMonthDate(referenceDate: Date, monthsAgo: number, targetDay: number, clampToToday = false): string {
  const targetMonth = subMonths(referenceDate, monthsAgo);
  const year = targetMonth.getFullYear();
  const monthIndex = targetMonth.getMonth();
  const daysInMonth = new Date(year, monthIndex + 1, 0).getDate();
  const maxDay = clampToToday && monthsAgo === 0 ? Math.min(daysInMonth, referenceDate.getDate()) : daysInMonth;
  const safeDay = Math.max(1, Math.min(targetDay, maxDay));
  return format(new Date(year, monthIndex, safeDay), 'yyyy-MM-dd');
}

